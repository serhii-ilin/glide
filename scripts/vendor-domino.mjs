#!/usr/bin/env node
/**
 * Bundle third_party/domino/lib/*.js into src/js/vendor/domino.js
 * with a small CommonJS loader (Node cycle semantics).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const LIB = path.join(ROOT, "third_party/domino/lib");
const OUT = path.join(ROOT, "src/js/vendor/domino.js");

function collectJsFiles(dir, base = "") {
  const out = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${ent.name}` : ent.name;
  if (ent.isDirectory()) {
      out.push(...collectJsFiles(path.join(dir, ent.name), rel));
    } else if (ent.name.endsWith(".js")) {
      out.push(rel);
    }
  }
  return out.sort();
}

function main() {
  if (!fs.existsSync(LIB)) {
    console.error(`missing ${LIB}; copy domino@2.1.9 lib/ into third_party/domino/`);
    process.exit(1);
  }
  const files = collectJsFiles(LIB);
  const modules = {};
  for (const rel of files) {
    const abs = path.join(LIB, rel);
    const body = fs.readFileSync(abs, "utf8");
    const key = `./lib/${rel.replace(/\\/g, "/")}`;
    modules[key] = body;
  }
  const moduleKeys = Object.keys(modules).sort();

  let out = `// Generated by scripts/vendor-domino.mjs — do not edit.\n`;
  out += `// Domino 2.1.9 (BSD-2-Clause). See third_party/domino/.\n`;
  out += `var global = globalThis;\n`;
  out += `globalThis.self = globalThis.window = globalThis;\n`;
  out += `globalThis.setTimeout = globalThis.setTimeout || function (fn) { queueMicrotask(fn); return 1; };\n`;
  out += `globalThis.clearTimeout = globalThis.clearTimeout || function () {};\n`;
  out += `globalThis.setInterval = globalThis.setInterval || globalThis.setTimeout;\n`;
  out += `globalThis.clearInterval = globalThis.clearInterval || function () {};\n\n`;
  out += `(function () {\n  'use strict';\n`;
  out += `  const moduleCache = Object.create(null);\n`;
  out += `  const moduleDefs = {\n`;

  for (const key of moduleKeys) {
    const srcJson = JSON.stringify(modules[key]);
    out += `    ${JSON.stringify(key)}: function (module, exports, require) {\n`;
    out += `      (new Function('module', 'exports', 'require', ${srcJson}))(module, exports, require);\n`;
    out += `    },\n`;
  }
  out += `  };\n\n`;

  out += `  function resolveId(from, request) {\n`;
  out += `    if (request === 'domino') return './lib/index.js';\n`;
  out += `    if (request.startsWith('./') || request.startsWith('../')) {\n`;
  out += `      const fromDir = from.replace(/\\/[^/]+$/, '');\n`;
  out += `      const joined = (fromDir + '/' + request).split('/');\n`;
  out += `      const stack = [];\n`;
  out += `      for (const p of joined) {\n`;
  out += `        if (!p || p === '.') continue;\n`;
  out += `        if (p === '..') stack.pop();\n`;
  out += `        else stack.push(p);\n`;
  out += `      }\n`;
  out += `      let id = './' + stack.join('/');\n`;
  out += `      if (!id.endsWith('.js')) id += '.js';\n`;
  out += `      return id;\n`;
  out += `    }\n`;
  out += `    return './lib/' + request + (request.endsWith('.js') ? '' : '.js');\n`;
  out += `  }\n\n`;
  out += `  function makeRequire(parentId) {\n`;
  out += `    return function require(request) {\n`;
  out += `      const id = resolveId(parentId, request);\n`;
  out += `      if (!moduleDefs[id]) {\n`;
  out += `        throw new Error('Cannot find module ' + request + ' from ' + parentId + ' (resolved ' + id + ')');\n`;
  out += `      }\n`;
  out += `      if (moduleCache[id]) return moduleCache[id].exports;\n`;
  out += `      const module = { exports: {} };\n`;
  out += `      moduleCache[id] = module;\n`;
  out += `      moduleDefs[id](module, module.exports, makeRequire(id));\n`;
  out += `      return module.exports;\n`;
  out += `    };\n`;
  out += `  }\n\n`;
  out += `  const dominoEntry = './lib/index.js';\n`;
  out += `  const dominoModule = { exports: {} };\n`;
  out += `  moduleCache[dominoEntry] = dominoModule;\n`;
  out += `  moduleDefs[dominoEntry](dominoModule, dominoModule.exports, makeRequire(dominoEntry));\n`;
  out += `  const domino = dominoModule.exports;\n`;
  out += `  global.__glide_domino = domino;\n`;
  out += `  globalThis.__glide_domino = domino;\n`;
  out += `})();\n`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
  console.log(`Wrote ${OUT} (${kb} KiB, ${files.length} modules)`);
}

main();